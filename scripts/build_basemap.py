"""Build the world land outline for the collaboration map.

Usage:
    python scripts/build_basemap.py

Source: Natural Earth 1:50m land (public domain). Equirectangular projection of
the whole world (Antarctica cropped) at 10 units per degree, so the map can be
zoomed from Europe out to the world. Writes:
  static/images/basemap-land.svg  the land outline (loaded by the map as an image)
  data/basemap.json               projection parameters used by sitegen/collab_map.py
Standard library only.
"""
from __future__ import annotations

import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_land.geojson"
BBOX = {"lon_min": -180.0, "lon_max": 180.0, "lat_min": -58.0, "lat_max": 78.0}
UNITS_PER_DEGREE = 10.0
LAND_FILL = "#e8ebea"   # drawn at low opacity on the dark band
MIN_STEP = 1.6          # drop points closer than this (in map units)
MIN_EXTENT = 4.0        # drop islands smaller than this (in map units)


def main() -> None:
    with urllib.request.urlopen(urllib.request.Request(SRC, headers={"User-Agent": "site-build"}), timeout=120) as r:
        geo = json.load(r)
    k = UNITS_PER_DEGREE
    width = (BBOX["lon_max"] - BBOX["lon_min"]) * k
    height = (BBOX["lat_max"] - BBOX["lat_min"]) * k

    def project(lon: float, lat: float) -> tuple[float, float]:
        return (lon - BBOX["lon_min"]) * k, (BBOX["lat_max"] - lat) * k

    parts = []
    for feat in geo["features"]:
        g = feat["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for poly in polys:
            for ring in poly:
                kept = []
                for lon, lat in ring:
                    x, y = project(lon, lat)
                    y = min(max(y, -2), height + 2)
                    if not kept or abs(x - kept[-1][0]) + abs(y - kept[-1][1]) >= MIN_STEP:
                        kept.append((x, y))
                xs = [p[0] for p in kept]
                ys = [p[1] for p in kept]
                if len(kept) < 3 or min(ys) > height or max(max(xs) - min(xs), max(ys) - min(ys)) < MIN_EXTENT:
                    continue
                # Relative, integer path commands keep the file small.
                pts = [(round(x), round(y)) for x, y in kept]
                deltas = [f"{x1 - x0} {y1 - y0}" for (x0, y0), (x1, y1) in zip(pts, pts[1:]) if (x1, y1) != (x0, y0)]
                parts.append(f"M{pts[0][0]} {pts[0][1]}l" + " ".join(deltas) + "z")
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.0f} {height:.0f}">'
           f'<path fill="{LAND_FILL}" d="{"".join(parts)}"/></svg>\n')
    (ROOT / "static/images/basemap-land.svg").write_text(svg, encoding="utf-8")
    meta = {
        "_note": "Generated by scripts/build_basemap.py from Natural Earth 1:50m land (public domain).",
        "bbox": BBOX, "width": width, "height": height, "image": "/images/basemap-land.svg",
    }
    (ROOT / "data/basemap.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"{len(parts)} rings, {len(svg) // 1024} KB, {width:.0f}x{height:.0f}")


if __name__ == "__main__":
    main()
