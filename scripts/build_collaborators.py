"""Build data/collaborators.json from co-author affiliations of the publications.

Usage:
    python scripts/build_collaborators.py

For every article with a DOI in data/publications.json, OpenAlex (openalex.org) is
asked for the authors' institutions. Institutions are merged, given coordinates from
OpenAlex, and linked to the co-authors and papers they come from. Urban's own
affiliation (the map centre) comes from data/profile.json. Re-run after adding
publications, then review the output: OpenAlex affiliations can be incomplete.
Standard library only.
"""
from __future__ import annotations

import json
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UA = {"User-Agent": "UrbanDajcmanSite/1.0 (academic website; collaborator map)"}
SELF_NAMES = {"urban dajčman", "urban dajcman", "u. dajčman"}


def get_json(url: str) -> dict:
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                return json.load(r)
        except Exception as exc:  # noqa: BLE001 - retry on rate limits and timeouts
            print("  retry", attempt + 1, exc)
            time.sleep(5 * (attempt + 1))
    raise RuntimeError(url)


def main() -> None:
    pubs = json.load(open(ROOT / "data/publications.json", encoding="utf-8"))["items"]
    articles = [p for p in pubs if p.get("type", "article") == "article" and p.get("doi")]
    institutions: dict[str, dict] = {}
    for pub in articles:
        print(pub["doi"])
        work = get_json("https://api.openalex.org/works/doi:" + urllib.parse.quote(pub["doi"]))
        for a in work.get("authorships", []):
            name = a["author"]["display_name"]
            if name.lower() in SELF_NAMES:
                continue
            for inst in a.get("institutions", []):
                iid = inst["id"].rsplit("/", 1)[-1]
                rec = institutions.setdefault(iid, {
                    "id": iid, "name": inst["display_name"], "country": inst.get("country_code"),
                    "people": set(), "papers": set(),
                })
                rec["people"].add(name)
                rec["papers"].add(pub["id"])
        time.sleep(0.5)

    # Coordinates, one batched request per 50 institutions.
    ids = list(institutions)
    for i in range(0, len(ids), 50):
        chunk = ids[i:i + 50]
        res = get_json("https://api.openalex.org/institutions?per-page=50&filter=openalex:" + "|".join(chunk))
        for inst in res["results"]:
            iid = inst["id"].rsplit("/", 1)[-1]
            geo = inst.get("geo") or {}
            institutions[iid].update({"city": geo.get("city"), "lat": geo.get("latitude"), "lon": geo.get("longitude")})

    out = []
    for rec in institutions.values():
        if rec.get("lat") is None:
            continue
        out.append({**rec, "people": sorted(rec["people"]), "papers": sorted(rec["papers"])})
    out.sort(key=lambda r: (-len(r["papers"]), r["name"]))
    data = {
        "_note": "Generated by scripts/build_collaborators.py from OpenAlex co-author affiliations of the publications in data/publications.json. Review before publishing; edit 'exclude' to hide an institution by id.",
        "exclude": [],
        "institutions": out,
    }
    path = ROOT / "data/collaborators.json"
    old = json.load(open(path, encoding="utf-8")) if path.exists() else {}
    # Keep hand-made corrections across re-runs.
    data["exclude"] = old.get("exclude", [])
    data["name_fixes"] = old.get("name_fixes", {})
    data["place_fixes"] = old.get("place_fixes", {})
    if "_exclude_note" in old:
        data["_exclude_note"] = old["_exclude_note"]
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for r in out:
        print(f'{len(r["papers"]):>2}  {r["name"]} ({r.get("city")}, {r["country"]})  {", ".join(r["people"])}')


if __name__ == "__main__":
    main()
